const englishRuntimePatterns = [
  [/^转写失败：(.+)$/, ([, detail]) => `Transcription failed: ${localizeRuntimeMessage("en", detail)}`],
  [/^录音保存失败：(.+)$/, ([, detail]) => `Could not save recording: ${localizeRuntimeMessage("en", detail)}`],
  [/^截图失败：(.+)$/, ([, detail]) => `Screenshot failed: ${localizeRuntimeMessage("en", detail)}`],
  [/^本地翻译不可用：(.+)$/, ([, detail]) => `Local translation is unavailable: ${detail}`],
  [/^标记不存在：(.+)$/, ([, id]) => `Note not found: ${id}`],
  [/^不支持的平台：(.+)$/, ([, platform]) => `Unsupported platform: ${platform}`],
  [/^侧栏缩放 (\d+)%$/, ([, zoom]) => `Side panel zoom: ${zoom}%`],
];

export function normalizeLanguage(value) {
  const normalized = String(value ?? "").trim().replaceAll("-", "_").toLowerCase();
  if (normalized === "zh" || normalized === "zh_cn" || normalized.startsWith("zh_")) return "zh_CN";
  if (normalized === "en" || normalized.startsWith("en_")) return "en";
  return null;
}

export function resolveLanguage(preference, uiLanguage) {
  return normalizeLanguage(preference) ?? normalizeLanguage(uiLanguage) ?? "en";
}

export function translate(language, key, variables = {}) {
  const resolved = normalizeLanguage(language) ?? "en";
  const template = messages[resolved]?.[key];
  if (!template) return key;
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/g, (match, name) => (
    Object.hasOwn(variables, name) ? String(variables[name]) : match
  ));
}

export function localizeRuntimeMessage(language, message) {
  const text = String(message ?? "");
  if (normalizeLanguage(language) !== "en") return text;
  const exact = englishRuntimeMessages.get(text);
  if (exact) return exact;
  for (const [pattern, replacement] of englishRuntimePatterns) {
    const match = text.match(pattern);
    if (match) return replacement(match);
  }
  return text;
}
